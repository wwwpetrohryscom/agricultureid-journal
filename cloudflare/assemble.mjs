#!/usr/bin/env node
/**
 * Post-build: assemble `dist/`, the directory the `agricultureid-journal`
 * Worker serves (wrangler.jsonc), from Next's static export in `out/`.
 *
 * The export is written WITHOUT the basePath — out/index.html, out/news.html,
 * out/_next/… — while every URL the pages emit begins with /journal. The asset
 * handler maps request paths straight onto files, so the export is placed
 * under dist/journal/ to make the two agree:
 *
 *   /journal/news               → dist/journal/news.html
 *   /journal/_next/static/…     → dist/journal/_next/static/…
 *   /journal/feed.json          → dist/journal/feed.json
 *
 * The front page is the exception. Left at dist/journal/index.html it would be
 * the DIRECTORY form, and the asset handler would answer the canonical
 * /journal with a redirect to /journal/. It is moved to dist/journal.html so
 * /journal is served directly and /journal/ is the one that redirects.
 *
 * Also written:
 *   dist/_headers    security headers on every path, immutable caching for
 *                    hashed chunks, and the feed media types the Netlify-era
 *                    route handlers sent (the asset handler would otherwise
 *                    infer them from the extension).
 *   dist/_redirects  trailing slash → no slash with a 308, the status Next
 *                    returned for `trailingSlash: false`.
 */
import { cpSync, existsSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { SECURITY_HEADERS } from './security-headers.mjs';

const ROOT = process.cwd();
const OUT = join(ROOT, 'out');
const DIST = join(ROOT, 'dist');
const BASE = 'journal';

if (!existsSync(join(OUT, 'index.html'))) {
  console.error('assemble: out/index.html missing — run `next build` first');
  process.exit(1);
}

rmSync(DIST, { recursive: true, force: true });
cpSync(OUT, join(DIST, BASE), { recursive: true });
renameSync(join(DIST, BASE, 'index.html'), join(DIST, `${BASE}.html`));

const FEED_TYPES = {
  'rss.xml': 'application/rss+xml; charset=utf-8',
  'atom.xml': 'application/atom+xml; charset=utf-8',
  'feed.json': 'application/feed+json; charset=utf-8',
  'sitemap.xml': 'application/xml; charset=utf-8',
  'latest.json': 'application/json; charset=utf-8',
  'search-index.json': 'application/json; charset=utf-8',
};
for (const file of Object.keys(FEED_TYPES)) {
  if (!existsSync(join(DIST, BASE, file))) {
    console.error(`assemble: the export has no ${file}`);
    process.exit(1);
  }
}

const security = SECURITY_HEADERS.map((h) => `  ${h.key}: ${h.value}`);
const headers = [
  '# Generated by cloudflare/assemble.mjs — do not edit.',
  `/${BASE}`,
  ...security,
  '',
  `/${BASE}/*`,
  ...security,
  '',
  `/${BASE}/_next/static/*`,
  '  Cache-Control: public, max-age=31536000, immutable',
  '',
  ...Object.entries(FEED_TYPES).flatMap(([file, type]) => [
    `/${BASE}/${file}`,
    `  Content-Type: ${type}`,
    '',
  ]),
].join('\n');

const redirects = [
  '# Generated by cloudflare/assemble.mjs — do not edit.',
  '/*/ /:splat 308',
  '',
].join('\n');

writeFileSync(join(DIST, '_headers'), headers);
writeFileSync(join(DIST, '_redirects'), redirects);
console.log(
  `assemble: dist/ ready (export under /${BASE}, front page at /${BASE}.html)`,
);
